// Палитра для рандомизации цвета embed'а
const JOKE_COLORS = [
    0x5865F2, // индиго
    0x57F287, // зелёный
    0xFEE75C, // жёлтый
    0xEB459E, // розовый
    0xED4245, // красный
    0x9B59B6, // фиолет
    0x3498DB, // синий
    0xFF9500, // оранжевый
    0x1ABC9C  // бирюза
];

function getRandomJoke(lastJoke = null) {
    const available = lastJoke ? JOKES.filter(j => j !== lastJoke) : JOKES;
    const pool = available.length > 0 ? available : JOKES;
    return pool[Math.floor(Math.random() * pool.length)];
}

function getRandomColor(lastColor = null) {
    let color;
    do {
        color = JOKE_COLORS[Math.floor(Math.random() * JOKE_COLORS.length)];
    } while (color === lastColor && JOKE_COLORS.length > 1);
    return color;
}

function createJokeEmbed(joke, color = null) {
    return new EmbedBuilder()
        .setTitle('😂 Шутка дня')
        .setDescription(`### ${joke.category}\n>>> ${joke.text}`)
        .setColor(color ?? getRandomColor())
        .setFooter({ text: `🎰 Всего шуток в базе: ${JOKES.length}` })
        .setTimestamp();
}

async function sendJoke(client, state) {
    try {
        const channel = await client.channels.fetch(JOKES_CHANNEL_ID);
        if (!channel) {
            console.error(`❌ Канал с ID ${JOKES_CHANNEL_ID} не найден.`);
            return false;
        }
        const botMember = channel.guild.members.me;
        if (!channel.permissionsFor(botMember).has(['SendMessages', 'EmbedLinks'])) {
            console.error(`❌ Бот не имеет прав на отправку сообщений или Embed-ссылок в канале ${JOKES_CHANNEL_ID}`);
            return false;
        }
        const joke = getRandomJoke(state.last);
        const color = getRandomColor(state.lastColor);
        state.last = joke;
        state.lastColor = color;
        const embed = createJokeEmbed(joke, color);
        await channel.send({ embeds: [embed] });
        console.log(`✅ Шутка отправлена автоматически (${joke.category})`);
        return true;
    } catch (error) {
        console.error('❌ Ошибка при автоматической отправке шутки:', error);
        return false;
    }
}

export default function(client) {
    // Общее состояние: последняя шутка/цвет — чтобы не повторяться подряд
    const state = { last: null, lastColor: null };

    client.once('clientReady', async () => {
        try {
            await client.application.commands.create({
                name: 'joke',
                description: 'Получить случайную шутку про CS2 и гейминг немедленно!'
            });
            console.log(`✅ Команда /joke зарегистрирована (в базе ${JOKES.length} шуток, интервал ${JOKE_INTERVAL_MS / 60000} мин)`);
        } catch (error) {
            console.error('❌ Ошибка при регистрации команды /joke:', error);
        }

        console.log(`📝 Первая шутка будет отправлена через ${JOKE_INITIAL_DELAY_MS / 1000} секунд.`);

        setTimeout(async () => {
            await sendJoke(client, state);
            setInterval(async () => {
                await sendJoke(client, state);
            }, JOKE_INTERVAL_MS);
        }, JOKE_INITIAL_DELAY_MS);
    });

    client.on('interactionCreate', async interaction => {
        if (!interaction.isChatInputCommand()) return;
        if (interaction.commandName !== 'joke') return;
        if (client.handledInteractions?.has(interaction.id)) return;
        client.handledInteractions?.add(interaction.id);

        const joke = getRandomJoke(state.last);
        state.last = joke;
        const color = getRandomColor(state.lastColor);
        state.lastColor = color;
        const embed = createJokeEmbed(joke, color);
        await interaction.reply({ embeds: [embed] });
    });
}
